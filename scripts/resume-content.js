function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function renderJobs(jobs, listStyle = "disc") {
  const listClass = listStyle === "disc" ? "disc" : "custom";
  return jobs
    .map(
      (job) => `
                <div class="job">
                    <div class="job-header">
                        <div>
                            <div class="job-title">${escapeHtml(job.title)}</div>
                            <div class="job-company">${escapeHtml(job.company)} | ${escapeHtml(job.location)}</div>
                        </div>
                        <div class="job-dates">${escapeHtml(job.dates)}</div>
                    </div>
                    <div class="job-description">
                        <ul>
                            ${job.bullets.map((b) => `<li>${escapeHtml(b)}</li>`).join("\n                            ")}
                        </ul>
                    </div>
                </div>`
    )
    .join("\n");
}

